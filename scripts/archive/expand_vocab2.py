for bid in report:
    for c in doc[bid]["cards"]:
        assert not re.search(r"[\u4e00-\u9fff\u3000-\u303f]", json.dumps(c, ensure_ascii=False)), c
ids_all = [norm(c["de"]) for b in doc.values() for c in b["cards"]]
assert len(ids_all) == len(set(ids_all)), "ازدواج متبقٍ في البنك كله!"
