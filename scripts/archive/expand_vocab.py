# ── توليد وفحص ذاتي صارم ──
doc = json.load(open("content/vocab.json"))
old_ids = {c["de"] for b in doc.values() for c in b["cards"]}
old_num = max(int(m.group(1)) for c in [c for b in doc.values() for c in b["cards"]] for m in [re.match(r"v(\d+)", c["id"])] if m)
seen = set(old_ids)
nxt = old_num + 1
added_total = 0
for bid, (tde, tar, rows) in U.items():
    cards = []
    for de, ar, lv, pl in rows:
        de, ar = (de or "").strip(), (ar or "").strip()
        if not de or not ar:
            print(f"⏭ {bid}: سطر ناقص مُتجاهَل: {de!r}"); continue
        assert "?" not in de + ar and not re.search(r"[\u4e00-\u9fff]", de), de
        assert re.match(r"^(der|die|das) |\S", de), de
        assert lv in ("A1", "A2", "B1", "B2"), de
        if de.lower() in seen:
            print(f"⏭ {bid}: ازدواج متجاهَل: {de}"); continue
        seen.add(de.lower())
        card = {"id": f"v{nxt}", "de": de, "ar": ar, "level": lv, "tags": [bid.split("-", 1)[1]]}
        if re.match(r"^(der|die|das) ", de):
            card["article"] = de.split(" ", 1)[0]
            if pl:
                assert pl.startswith("die "), pl
                card["plural"] = pl
        cards.append(card)
        nxt += 1
    assert len(cards) >= 40, f"{bid}: {len(cards)} فقط — دون 40"
    doc[bid] = {"id": bid, "titleDe": tde, "titleAr": tar, "level": "B2", "cards": cards}
    added_total += len(cards)
    print(f"✓ {bid}: {len(cards)} بطاقة")
json.dump(doc, open("content/vocab.json", "w"), ensure_ascii=False, indent=1)
total = sum(len(b["cards"]) for b in doc.values())
print(f"المضاف {added_total} · الإجمالي في vocab.json: {total} بطاقة")
