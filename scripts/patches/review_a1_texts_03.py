def main() -> None:
    data = json.loads(TEXTS.read_text(encoding="utf-8"))
    expected = sum(len(v) for v in PROMPTS.values())
    applied = 0
    for t in data:
        tid = t.get("id")
        if tid not in PROMPTS: continue
        for qi, ar in PROMPTS[tid].items():
            q = t["questions"][qi]
            if not q.get("promptAr","").strip():
                q["promptAr"] = ar
                applied += 1
    assert applied == expected, (applied, expected)
    TEXTS.write_text(json.dumps(data, ensure_ascii=False, indent=2)+"\n", encoding="utf-8")
    print(f"<R138> patch complete · changes applied: {applied} · locked titles: {len(data)}")


if __name__ == "__main__": main()
